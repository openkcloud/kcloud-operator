#!/usr/bin/env bash
# ============================================================
# private-ip-check.sh: 내부 주소·계정이 추적 파일에 들어오는 것을 막는다
# 상세: 공개 저장소로 나가면 안 되는 문자열을 추적 파일에서 찾는다. 사내 대역 두 개와
#       RFC1918 사설 대역, 내부 계정, 기본 인증 문자열이 대상이다. hack/public-chain.sh
#       의 PRIV_RE 를 포함하되 그것이 놓치던 192.168 대역과 10.0.x 사내 Harbor 도 잡는다.
#       kind·Docker 브리지 대역(172.17~172.31)은 컨테이너가 매번 새로 받는 값이라 뺀다.
#       예외는 아래 ALLOW 에 이유와 함께 적는다.
# 생성일: 2026-09-30
# ============================================================
set -euo pipefail
cd "$(dirname "$0")/.."

# 사내 대역 둘, RFC1918 사설 대역 셋, 내부 계정, 기본 인증.
# 172.16/12 는 컨테이너 런타임이 쓰는 구간이라 뺀다 — 노출돼도 내부 정보가 아니다.
PRIV_RE='(^|[^0-9.])(10\.254\.|129\.254\.|192\.168\.|10\.0\.[0-9]+\.)[0-9]|[A-Za-z0-9._-]+@(10\.254\.|129\.254\.|192\.168\.|10\.0\.[0-9]+\.)[0-9]|admin:[A-Za-z0-9]'

# 예외. 각 줄은 "경로:이유" 다.
#   (지금 없음)
ALLOW='^$'

hits=$(git ls-files \
  | grep -vE "$ALLOW" \
  | xargs grep -nIE "$PRIV_RE" 2>/dev/null || true)

if [ -n "$hits" ]; then
  echo "내부 주소나 계정이 추적 파일에 있다. 공개 저장소로 나가면 안 된다."
  echo "주소는 환경변수로 받고 산문에는 자리표시자를 쓴다."
  echo
  echo "$hits"
  exit 1
fi
echo "내부 주소 검사 통과"
